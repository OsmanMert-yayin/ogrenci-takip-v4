/**
 * Milat Koruması: Otomatik Ezber "Vermedi" motoru yalnızca 2026-11-27 ve sonrası
 * tarihler için çalışır; geçmişe dönük toplu ceza/engel üretmez.
 */
export const AUTO_EZBER_MILAT_DATE = '2026-11-27';

export interface TelegramDispatchTask {
  studentId: string;
  studentName: string;
  chatId: string;
  message: string;
  logKey: string;
}

export interface AutoEzberCheckResult {
  newLessons: LessonUpsertInput[];
  logKeys: string[];
}

export function isTimeReached(targetHHmm: string, currentHHmm: string): boolean {
  if (!/^\d{2}:\d{2}$/.test(targetHHmm)) return false;
  return currentHHmm >= targetHHmm;
}

/**
 * Milat korumalı Ezber otomatik "Vermedi" kontrolü:
 * - dateISO >= 2026-11-27 olmalı
 * - Aktif öğrencilerde o günün programında "Ezber" dersi varsa
 * - Öğrenci o gün tam gün "Gelmedi" veya "İzinli" değilse
 * - O gün için henüz Ezber ders kaydı girilmemişse
 * - automationLog içinde aynı gün+öğrenci kilidi yoksa
 * isAutoGenerated: true ile gerçek "Vermedi" kaydı üretir.
 */
export function computeAutoEzberVermedi(
  db: AppDatabase,
  activeTermId: string,
  dateISO: string
): AutoEzberCheckResult {
  if (dateISO < AUTO_EZBER_MILAT_DATE) {
    return { newLessons: [], logKeys: [] };
  }

  const newLessons: LessonUpsertInput[] = [];
  const logKeys: string[] = [];
  const activeStudents = db.students.filter((s) => s.status === 'Aktif');
  const nowHHmm = getCurrentTimeHHmm();

  for (const student of activeStudents) {
    const logKey = `auto_ezber|${dateISO}|${student.id}`;
    if (db.automationLog?.[logKey]) continue;

    // 1. Tam gün Gelmedi veya İzinli kontrolü
    const fullDayRec = db.attendance.find(
      (a) =>
        a.date === dateISO &&
        a.studentId === student.id &&
        a.lessonSlotId === DAILY_ATTENDANCE_SLOT_ID
    );
    if (fullDayRec && (fullDayRec.status === 'Gelmedi' || fullDayRec.status === 'İzinli')) {
      continue;
    }

    // 2. O günkü programda Ezber var mı?
    const dailySubjects = resolveDailySubjectsForClass(
      db.schedule,
      db.lessonSlots,
      activeTermId,
      student.classId,
      dateISO
    );
    const ezberTpl = dailySubjects.find(
      (s) => s.subjectName.trim().toLocaleLowerCase('tr-TR') === 'ezber'
    );
    if (!ezberTpl) continue;

    // 3. Bugün zaten Ezber kaydı girilmiş mi?
    const hasEzberRecord = db.lessons.some(
      (l) =>
        l.date === dateISO &&
        l.studentId === student.id &&
        inferLessonSubject(l).toLocaleLowerCase('tr-TR') === 'ezber'
    );
    if (hasEzberRecord) {
      logKeys.push(logKey);
      continue;
    }

    newLessons.push({
      date: dateISO,
      studentId: student.id,
      classId: student.classId,
      lessonSlotId: ezberTpl.firstSlotId,
      subjectName: 'Ezber',
      topicTitle: ezberTpl.defaultTopic || 'Ezber',
      status: 'Vermedi',
      evaluation: 'Dinlenmedi',
      turCount: 1,
      isAutoGenerated: true,
      recordedTime: nowHHmm,
      note: 'Otomatik Ezber Vermedi kaydı',
    });
    logKeys.push(logKey);
  }

  return { newLessons, logKeys };
}

export interface BatchNotificationPlan {
  whatsappItems: WhatsAppQueueItem[];
  telegramTasks: TelegramDispatchTask[];
  logKeys: string[];
}

export function buildDailyReportPlan(
  db: AppDatabase,
  activeTermId: string,
  dateISO: string,
  options?: {
    studentIds?: string[];
    ignoreProcessedLog?: boolean;
    extraLessons?: LessonRecord[];
  }
): BatchNotificationPlan {
  const activeStudents = db.students.filter((s) => s.status === 'Aktif');
  const targetStudents = options?.studentIds
    ? activeStudents.filter((s) => options.studentIds!.includes(s.id))
    : activeStudents;
  const classMap = new Map(db.classes.map((c) => [c.id, c]));
  const combinedLessons = options?.extraLessons
    ? [...db.lessons, ...options.extraLessons]
    : db.lessons;
  const channel = db.automation.dailyReportChannel || 'whatsapp';
  const nowIso = new Date().toISOString();

  const whatsappItems: WhatsAppQueueItem[] = [];
  const telegramTasks: TelegramDispatchTask[] = [];
  const logKeys: string[] = [];

  for (const student of targetStudents) {
    const logKey = `daily_report|${dateISO}|${student.id}`;
    if (!options?.ignoreProcessedLog && db.automationLog?.[logKey]) continue;

    const guardian = getPrimaryGuardian(student);
    if (!guardian || guardian.notificationPreference === 'Bildirim İstemiyor') continue;

    const message = buildDailyStudentReportMessage({
      student,
      classGroup: classMap.get(student.classId),
      dateISO,
      activeTermId,
      attendance: db.attendance,
      lessons: combinedLessons,
      schedule: db.schedule,
      lessonSlots: db.lessonSlots,
      exams: db.exams,
      grades: db.grades,
      gradingSettings: db.gradingSettings,
      allActiveStudents: activeStudents,
      automation: db.automation,
    });

    const wantsWa = channel === 'whatsapp' || channel === 'both';
    const wantsTg = channel === 'telegram' || channel === 'both';

    if (wantsWa && guardian.phone.trim()) {
      whatsappItems.push({
        id: createId('waq'),
        studentId: student.id,
        studentName: student.fullName,
        guardianName: guardian.fullName,
        guardianPhone: guardian.phone,
        category: 'dailyReport',
        label: 'Günlük Rapor',
        message,
        createdAt: nowIso,
      });
    }

    if (wantsTg && db.automation.telegramBotToken?.trim() && guardian.telegramChatId?.trim()) {
      telegramTasks.push({
        studentId: student.id,
        studentName: student.fullName,
        chatId: guardian.telegramChatId.trim(),
        message,
        logKey,
      });
    }

    logKeys.push(logKey);
  }

  return { whatsappItems, telegramTasks, logKeys };
}

export function resolveSubjectForAttendanceRecord(
  db: AppDatabase,
  activeTermId: string,
  record: AttendanceRecord
): string | undefined {
  if (record.lessonSlotId === DAILY_ATTENDANCE_SLOT_ID) return undefined;
  const dow = getDayOfWeekFromISO(record.date);
  const exact = db.schedule.find(
    (s) =>
      s.termId === activeTermId &&
      s.classId === record.classId &&
      s.dayOfWeek === dow &&
      s.lessonSlotId === record.lessonSlotId
  );
  if (exact) return exact.subjectName;
  const general = db.schedule.find(
    (s) =>
      s.termId === activeTermId &&
      s.classId === '__general__' &&
      s.dayOfWeek === dow &&
      s.lessonSlotId === record.lessonSlotId
  );
  return general?.subjectName;
}

export function buildAttendanceAlertPlan(
  db: AppDatabase,
  activeTermId: string,
  records: AttendanceRecord[],
  ignoreProcessedLog = false
): BatchNotificationPlan {
  const studentMap = new Map<string, Student>(db.students.map((s) => [s.id, s]));
  const classMap = new Map(db.classes.map((c) => [c.id, c]));
  const slotMap = new Map(db.lessonSlots.map((s) => [s.id, s]));
  const channel = db.automation.attendanceChannel || 'whatsapp';
  const nowIso = new Date().toISOString();

  const whatsappItems: WhatsAppQueueItem[] = [];
  const telegramTasks: TelegramDispatchTask[] = [];
  const logKeys: string[] = [];

  for (const record of records) {
    if (!attendanceStatusToTemplateKey(record.status)) continue; // Skip 'Geldi'

    const logKey = `att_notify|${record.date}|${record.studentId}|${record.lessonSlotId}|${record.status}`;
    if (!ignoreProcessedLog && db.automationLog?.[logKey]) continue;

    const student = studentMap.get(record.studentId);
    if (!student || student.status !== 'Aktif') continue;

    const guardian = getPrimaryGuardian(student);
    if (!guardian || guardian.notificationPreference === 'Bildirim İstemiyor') continue;

    const subjectName = resolveSubjectForAttendanceRecord(db, activeTermId, record);
    const message = buildAttendanceNotificationMessage({
      student,
      classGroup: classMap.get(student.classId),
      record,
      slot: slotMap.get(record.lessonSlotId),
      subjectName,
      automation: db.automation,
    });

    const wantsWa = channel === 'whatsapp' || channel === 'both';
    const wantsTg = channel === 'telegram' || channel === 'both';

    if (wantsWa && guardian.phone.trim()) {
      whatsappItems.push({
        id: createId('waq'),
        studentId: student.id,
        studentName: student.fullName,
        guardianName: guardian.fullName,
        guardianPhone: guardian.phone,
        category: 'attendance',
        label: record.status,
        message,
        createdAt: nowIso,
      });
    }

    if (wantsTg && db.automation.telegramBotToken?.trim() && guardian.telegramChatId?.trim()) {
      telegramTasks.push({
        studentId: student.id,
        studentName: student.fullName,
        chatId: guardian.telegramChatId.trim(),
        message,
        logKey,
      });
    }

    logKeys.push(logKey);
  }

  return { whatsappItems, telegramTasks, logKeys };
}

export interface ScheduledTickResult {
  autoEzberLessons: LessonUpsertInput[];
  whatsappItems: WhatsAppQueueItem[];
  telegramTasks: TelegramDispatchTask[];
  logKeys: string[];
}

/**
 * Dakikada bir (60.000 ms) çalışan hafif zamanlayıcı motoru.
 * ÖNCELİK SIRASI:
 * 1) Ezber Otomatik "Vermedi" (saati geldiyse ÖNCE çalışır)
 * 2) Planlı Yoklama Bildirimi (mod 'scheduled' ise)
 * 3) Planlı Günlük Ders Raporu (1. adımda üretilen oto-Ezber kayıtlarını anında dahil eder)
 */
export function evaluateScheduledAutomationTick(
  db: AppDatabase,
  activeTermId: string
): ScheduledTickResult {
  const todayISO = getTodayISO();
  const currentHHmm = getCurrentTimeHHmm();

  const autoEzberLessons: LessonUpsertInput[] = [];
  const whatsappItems: WhatsAppQueueItem[] = [];
  const telegramTasks: TelegramDispatchTask[] = [];
  const logKeys: string[] = [];

  // STEP 1: Auto-Ezber Vermedi FIRST (if enabled & time reached)
  const syntheticAutoLessons: LessonRecord[] = [];
  if (
    db.automation.autoEzberEnabled &&
    isTimeReached(db.automation.autoEzberTime || '17:00', currentHHmm)
  ) {
    const ezberResult = computeAutoEzberVermedi(db, activeTermId, todayISO);
    autoEzberLessons.push(...ezberResult.newLessons);
    logKeys.push(...ezberResult.logKeys);
    for (const item of ezberResult.newLessons) {
      syntheticAutoLessons.push({
        ...item,
        id: createId('lsn_auto_preview'),
        recordedTime: item.recordedTime || currentHHmm,
      });
    }
  }

  // STEP 2: Scheduled Attendance Alerts (when mode === 'scheduled')
  if (
    db.automation.attendanceMode === 'scheduled' &&
    isTimeReached(db.automation.attendanceTime || '11:00', currentHHmm)
  ) {
    const todayAtt = db.attendance.filter((a) => a.date === todayISO);
    const attPlan = buildAttendanceAlertPlan(db, activeTermId, todayAtt, false);
    whatsappItems.push(...attPlan.whatsappItems);
    telegramTasks.push(...attPlan.telegramTasks);
    logKeys.push(...attPlan.logKeys);
  }

  // STEP 3: Daily Report (runs AFTER Auto-Ezber so auto "Vermedi" records are included immediately!)
  if (
    db.automation.dailyReportMode === 'scheduled' &&
    isTimeReached(db.automation.dailyReportTime || '17:00', currentHHmm)
  ) {
    const reportPlan = buildDailyReportPlan(db, activeTermId, todayISO, {
      ignoreProcessedLog: false,
      extraLessons: syntheticAutoLessons,
    });
    whatsappItems.push(...reportPlan.whatsappItems);
    telegramTasks.push(...reportPlan.telegramTasks);
    logKeys.push(...reportPlan.logKeys);
  }

  return { autoEzberLessons, whatsappItems, telegramTasks, logKeys };
}
