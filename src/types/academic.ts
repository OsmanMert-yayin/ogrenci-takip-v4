export type LessonEvaluation = 'Pekiyi' | 'İyi' | 'Orta' | 'Tekrar' | 'Dinlenmedi';

export type LessonResultStatus = 'Geçti' | 'Tekrar' | 'Vermedi';

export interface LessonRecord {
  id: string;
  date: string; // YYYY-MM-DD
  studentId: string;
  classId: string;
  lessonSlotId?: string;
  subjectName?: string; // Yüzüne, Ezber, Talim Tecvid, Temel Dini Bilgiler, Hafızlık vb.
  topicId?: string;
  topicTitle: string;
  pageOrVerse?: string;
  amount?: string; // Örn: 1 Sayfa, 2 Sayfa, 1 Sure, 1 Kural
  score?: number; // 0-100
  status?: LessonResultStatus; // Geçti | Tekrar | Vermedi
  evaluation: LessonEvaluation;
  turCount: number; // Hafızlık/Ezber tur sayısı (en az 1)
  makeupOfId?: string; // Telafi edilen önceki Vermedi/Tekrar kaydının ID'si
  combinedSessionId?: string; // Birleştirilmiş oturum kimliği (Cuma izninde tek oturum)
  isAutoGenerated?: boolean; // Ezber otomatik "Vermedi" motoru tarafından oluşturulduysa true
  recordedTime: string; // HH:mm
  teacherId?: string;
  note?: string;
}

